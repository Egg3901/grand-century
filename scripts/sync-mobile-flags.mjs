// Requires librsvg's rsvg-convert. Runtime assets are committed and work offline.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const world = JSON.parse(
  await readFile(
    new URL("apps/mobile/assets/game/worldSeed.json", root),
    "utf8",
  ),
);
const output = new URL("apps/mobile/assets/flags/", root);
await mkdir(output, { recursive: true });
const entries = [];
for (const { tag } of [...world.nations].sort((a, b) =>
  a.tag.localeCompare(b.tag),
)) {
  const svg = new URL(`public/flags/${tag}.svg`, root);
  execFileSync("rsvg-convert", [
    "-w",
    "144",
    "-h",
    "96",
    "-o",
    fileURLToPath(new URL(`${tag}.png`, output)),
    fileURLToPath(svg),
  ]);
  entries.push(
    `  ${JSON.stringify(tag)}: require('../assets/flags/${tag}.png'),`,
  );
}
await writeFile(
  new URL("apps/mobile/game/nationFlags.ts", root),
  `// Generated by scripts/sync-mobile-flags.mjs from the web's authored flags.\nimport type {ImageSourcePropType} from 'react-native';\nexport const nationFlags: Record<string, ImageSourcePropType> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`Bundled ${entries.length} native country flags.`);
